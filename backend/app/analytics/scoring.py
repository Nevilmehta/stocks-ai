"""Deterministic AI Research Score.

This score is calculated entirely from financial ratios, growth trends, and
technical indicators - it is NOT generated by an AI model. An AI provider
(Gemini, later a custom model) is only ever asked to *explain* this score in
plain language; it never determines the numbers themselves. See
docs on AI hallucination protection - the goal is that every number shown to
a user is traceable back to a formula in this file.

Overall score = weighted average of six 0-100 subscores:
    Financial Strength   25%   (debt/equity, cash flow quality)
    Growth                20%   (revenue/profit/EPS growth)
    Profitability          20%   (ROE, ROCE, margins)
    Valuation                15%   (P/E, P/B vs sector peers)
    Technical Momentum   10%   (price vs moving averages, RSI, MACD)
    Risk (safety)            10%   (volatility, leverage, earnings consistency)

Each subscore is itself an unweighted average of a few normalized (0-100)
inputs - see the individual calculate_* functions below for exactly which
inputs and ranges are used.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.schemas.stock import FinancialPeriod, TechnicalIndicators
from app.schemas.strategy import DEFAULT_STRATEGY_CONFIG, StrategyConfig

# Kept for backward-compat readability/reference - compute_ai_score now reads
# weights from the active StrategyConfig instead of this dict.
WEIGHTS = {
    "financial_strength": 0.25,
    "growth": 0.20,
    "profitability": 0.20,
    "valuation": 0.15,
    "technical_momentum": 0.10,
    "risk": 0.10,
}


def normalize(value: float | None, low: float, high: float, default: float = 50.0) -> float:
    """Linearly maps value from [low, high] to [0, 100], clamped. None -> default (neutral)."""
    if value is None:
        return default
    if high == low:
        return default
    pct = (value - low) / (high - low) * 100
    return max(0.0, min(100.0, pct))


def normalize_inverse(value: float | None, low: float, high: float, default: float = 50.0) -> float:
    """Like normalize(), but a LOWER raw value produces a HIGHER score (e.g. debt, volatility)."""
    return 100.0 - normalize(value, low, high, default=100 - default)


def calculate_financial_strength(latest: FinancialPeriod, config: StrategyConfig = DEFAULT_STRATEGY_CONFIG) -> float:
    de_score = normalize_inverse(latest.debt_to_equity, config.debt_to_equity_good, config.debt_to_equity_bad)
    cash_ratio = (latest.operating_cash_flow / latest.net_profit) if latest.net_profit else None
    cash_score = normalize(cash_ratio, 0.5, 1.5)
    return round((de_score + cash_score) / 2, 1)


def _eps_growth_percent(annual_periods: list[FinancialPeriod]) -> float | None:
    if len(annual_periods) < 2:
        return None
    prev, latest = annual_periods[-2], annual_periods[-1]
    if not prev.eps:
        return None
    return (latest.eps - prev.eps) / abs(prev.eps) * 100


def calculate_growth(latest: FinancialPeriod, annual_periods: list[FinancialPeriod]) -> float:
    revenue_score = normalize(latest.revenue_growth, -5, 25)
    profit_score = normalize(latest.profit_growth, -10, 35)
    eps_growth = _eps_growth_percent(annual_periods)
    eps_score = normalize(eps_growth, -10, 35) if eps_growth is not None else profit_score
    return round(revenue_score * 0.3 + profit_score * 0.4 + eps_score * 0.3, 1)


def calculate_profitability(latest: FinancialPeriod, config: StrategyConfig = DEFAULT_STRATEGY_CONFIG) -> float:
    roe_score = normalize(latest.roe, config.roe_low, config.roe_high)
    roce_score = normalize(latest.roce, config.roce_low, config.roce_high)
    net_margin_score = normalize(latest.net_margin, 3, 25)
    operating_margin = (latest.operating_profit / latest.revenue * 100) if latest.revenue else None
    operating_margin_score = normalize(operating_margin, 5, 30)
    return round((roe_score + roce_score + net_margin_score + operating_margin_score) / 4, 1)


def calculate_valuation(
    latest: FinancialPeriod,
    peer_latest_periods: list[FinancialPeriod],
    config: StrategyConfig = DEFAULT_STRATEGY_CONFIG,
) -> float:
    peer_pes = [p.pe_ratio for p in peer_latest_periods if p.pe_ratio and p.pe_ratio > 0]
    peer_pbs = [p.pb_ratio for p in peer_latest_periods if p.pb_ratio and p.pb_ratio > 0]

    if peer_pes and latest.pe_ratio:
        relative_pe = latest.pe_ratio / (sum(peer_pes) / len(peer_pes))
        pe_score = normalize_inverse(relative_pe, 0.5, 2.0)
    else:
        pe_score = normalize_inverse(latest.pe_ratio, config.pe_fallback_low, config.pe_fallback_high)

    if peer_pbs and latest.pb_ratio:
        relative_pb = latest.pb_ratio / (sum(peer_pbs) / len(peer_pbs))
        pb_score = normalize_inverse(relative_pb, 0.5, 2.0)
    else:
        pb_score = normalize_inverse(latest.pb_ratio, 1, 8)

    return round((pe_score + pb_score) / 2, 1)


def calculate_technical_momentum(
    technicals: TechnicalIndicators, config: StrategyConfig = DEFAULT_STRATEGY_CONFIG
) -> float:
    sma50_score = normalize(technicals.price_vs_sma50_percent, -10, 10)
    sma200_score = normalize(technicals.price_vs_sma200_percent, -15, 15)
    rsi_score = normalize(technicals.rsi_14, config.rsi_oversold, config.rsi_overbought)

    macd_score = 50.0
    if technicals.macd_histogram is not None and technicals.sma_50:
        macd_relative_percent = technicals.macd_histogram / technicals.sma_50 * 100
        macd_score = normalize(macd_relative_percent, -2, 2)

    return round((sma50_score + sma200_score + rsi_score + macd_score) / 4, 1)


def calculate_risk_safety(
    technicals: TechnicalIndicators,
    latest: FinancialPeriod,
    annual_periods: list[FinancialPeriod],
    config: StrategyConfig = DEFAULT_STRATEGY_CONFIG,
) -> float:
    volatility_score = normalize_inverse(technicals.volatility, 15, 45)
    leverage_score = normalize_inverse(latest.debt_to_equity, config.debt_to_equity_good, config.debt_to_equity_bad)

    growths = [p.profit_growth for p in annual_periods if p.profit_growth is not None]
    if len(growths) >= 2:
        mean = sum(growths) / len(growths)
        variance = sum((g - mean) ** 2 for g in growths) / len(growths)
        stddev = variance**0.5
    else:
        stddev = 20.0  # unknown consistency -> neutral-ish penalty
    consistency_score = normalize_inverse(stddev, 5, 40)

    return round((volatility_score + leverage_score + consistency_score) / 3, 1)


def risk_label_from_safety_score(safety_score: float, config: StrategyConfig = DEFAULT_STRATEGY_CONFIG) -> str:
    if safety_score >= config.risk_low_cutoff:
        return "Low"
    if safety_score >= config.risk_moderate_cutoff:
        return "Moderate"
    return "High"


def overall_label(score: float, config: StrategyConfig = DEFAULT_STRATEGY_CONFIG) -> str:
    if score >= config.overall_very_strong_cutoff:
        return "Very Strong"
    if score >= config.overall_strong_cutoff:
        return "Strong"
    if score >= config.overall_balanced_cutoff:
        return "Balanced"
    if score >= config.overall_weak_cutoff:
        return "Weak"
    return "Very Weak"


@dataclass
class AIScoreResult:
    overall_score: int
    label: str
    risk_label: str
    financial_strength: float
    growth: float
    profitability: float
    valuation: float
    technical_momentum: float
    risk: float


def compute_ai_score(
    annual_periods: list[FinancialPeriod],
    technicals: TechnicalIndicators,
    peer_latest_periods: list[FinancialPeriod],
    config: StrategyConfig = DEFAULT_STRATEGY_CONFIG,
) -> AIScoreResult | None:
    """`annual_periods` must be ordered oldest -> newest. Returns None if there's
    no financial data at all (can't compute a meaningful score)."""
    if not annual_periods:
        return None

    latest = annual_periods[-1]

    financial_strength = calculate_financial_strength(latest, config)
    growth = calculate_growth(latest, annual_periods)
    profitability = calculate_profitability(latest, config)
    valuation = calculate_valuation(latest, peer_latest_periods, config)
    technical_momentum = calculate_technical_momentum(technicals, config)
    risk = calculate_risk_safety(technicals, latest, annual_periods, config)

    overall = (
        financial_strength * config.weight_financial_strength
        + growth * config.weight_growth
        + profitability * config.weight_profitability
        + valuation * config.weight_valuation
        + technical_momentum * config.weight_technical_momentum
        + risk * config.weight_risk
    )
    overall_rounded = round(max(0.0, min(100.0, overall)))

    return AIScoreResult(
        overall_score=overall_rounded,
        label=overall_label(overall_rounded, config),
        risk_label=risk_label_from_safety_score(risk, config),
        financial_strength=financial_strength,
        growth=growth,
        profitability=profitability,
        valuation=valuation,
        technical_momentum=technical_momentum,
        risk=risk,
    )
